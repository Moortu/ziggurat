//! The generated root of a project with no Zig scripts, as an export build
//! writes it (`rootgen.generateRoot` with no scripts and the build id
//! `export_build.build_id`; a test in export_build.zig checks that they
//! agree). build.zig compiles it with the SDK and links it with the export
//! host archive into `libziggurat_game_empty.so`, the library the export
//! plugin ships for a project without Zig scripts, so such a project
//! exports without a Zig build. Imports nothing, so build.zig can import it.

pub const text =
    \\//! Generated by Ziggurat. Do not edit; it is rewritten on every build.
    \\
    \\const ziggurat = @import("ziggurat");
    \\
    \\pub const panic = ziggurat.Panic;
    \\
    \\
    \\const scripts = ziggurat.scriptList(&.{});
    \\const table = ziggurat.tableOf(scripts, "export");
    \\
    \\export fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void {
    \\    ziggurat.moduleInit(api, gen);
    \\}
    \\
    \\export fn ziggurat_describe() callconv(.c) *const ziggurat.Table {
    \\    return &table;
    \\}
    \\
;

/// The same root as a Windows export build writes it
/// (`rootgen.RootOptions.hidden_exports`): the two entry points exported
/// with hidden visibility, so the empty game DLL exports only
/// `ziggurat_host_init`. build.zig compiles it into
/// `ziggurat_game_empty.dll`.
pub const hidden_text =
    \\//! Generated by Ziggurat. Do not edit; it is rewritten on every build.
    \\
    \\const ziggurat = @import("ziggurat");
    \\
    \\pub const panic = ziggurat.Panic;
    \\
    \\
    \\const scripts = ziggurat.scriptList(&.{});
    \\const table = ziggurat.tableOf(scripts, "export");
    \\
    \\fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void {
    \\    ziggurat.moduleInit(api, gen);
    \\}
    \\
    \\fn ziggurat_describe() callconv(.c) *const ziggurat.Table {
    \\    return &table;
    \\}
    \\
    \\comptime {
    \\    @export(&ziggurat_init, .{ .name = "ziggurat_init", .visibility = .hidden });
    \\    @export(&ziggurat_describe, .{ .name = "ziggurat_describe", .visibility = .hidden });
    \\}
    \\
;

/// The module-definition file of every Windows game library (an export
/// build's and the empty one): it exports only Godot's entry point. Without
/// it the COFF linker also exports the MinGW runtime's `_CRT_INIT`,
/// `__mingw_module_is_dll` and `atexit`. Kept here, next to the root
/// texts, so build.zig and `export_build` share it.
pub const module_definition = "EXPORTS\n    ziggurat_host_init\n";
