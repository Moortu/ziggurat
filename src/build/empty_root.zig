//! The generated root of a project with no Zig scripts, as an export build
//! writes it (`rootgen.generateRoot` with no scripts and the build id
//! `export_build.build_id`; a test in export_build.zig checks that they
//! agree). build.zig compiles it with the SDK and links it with the export
//! host archive into `libziggurat_game_empty.so`, the library the export
//! plugin ships for a project without Zig scripts, so such a project
//! exports without a Zig build. Imports nothing, so build.zig can import it.

pub const text =
    \\//! Generated by Ziggurat. Do not edit; it is rewritten on every build.
    \\
    \\const ziggurat = @import("ziggurat");
    \\
    \\pub const panic = ziggurat.Panic;
    \\
    \\
    \\const scripts = ziggurat.scriptList(&.{});
    \\const table = ziggurat.tableOf(scripts, "export");
    \\
    \\export fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void {
    \\    ziggurat.moduleInit(api, gen);
    \\}
    \\
    \\export fn ziggurat_describe() callconv(.c) *const ziggurat.Table {
    \\    return &table;
    \\}
    \\
;
