//! Generated root file (L2) and the root contract.
//!
//! The generated `.ziggurat_root.zig` sits at the project root, next to the
//! scripts, because a Zig module can only import files below its root's folder.
//! It imports the SDK as `@import("ziggurat")`. The Stage 2 SDK must provide
//! exactly this surface:
//!
//!   - `ziggurat.Panic`: the root has `pub const panic = ziggurat.Panic;`. It
//!     must be a panic namespace usable as a root `panic`, for example
//!     `std.debug.FullPanic(handler)`. `std.debug.simple_panic` does not
//!     compile in a `-lc` dynamic library with Zig 0.17.0.
//!   - `ziggurat.describe(comptime S: type, comptime rel: []const u8) ziggurat.ScriptDescriptor`,
//!     called once per script as
//!     `pub const s<i> = ziggurat.describe(@import(<import literal>), <rel literal>);`.
//!     `rel` is the script's project-relative path with `/` separators on
//!     every OS (for example `"a/x.zig"`), written as a Zig string literal
//!     escaped with `std.zig.fmtString`, so at comptime it holds the plain
//!     path. It exists for the SDK marker below: `@typeName(S)` cannot give
//!     the path back (`a b/q/x.y.zig` and `a b/q/x/y.zig` both give
//!     `a b.q.x.y`).
//!   - `ziggurat.Table`, built with
//!     `const table = ziggurat.makeTable(&.{ &s0, &s1, ... }, "<build id>");`.
//!     The first argument is a pointer to a tuple of `*const ScriptDescriptor`,
//!     which coerces to a slice `[]const *const ScriptDescriptor`. With no
//!     scripts it is `&.{}`. The second, `comptime build_id: []const u8`, is
//!     16 lowercase hex characters (`scan.ScanResult.build_id`: a hash of the
//!     path, size, times and inode of every scanned file) that the SDK
//!     stores in `Table.build_id`. After an incremental update the build
//!     service reads the id back from the staged library to catch a compiler
//!     that kept stale code.
//!   - `ziggurat.HostApi` and `ziggurat.moduleInit(api: *const ziggurat.HostApi, gen: u32) void`.
//!   - `HostApi` and `Table` cross a `dlopen` boundary into a host that is
//!     compiled separately, so their layout must be `extern` (or `packed`
//!     with a fixed backing integer). A Zig slice, as in the stub SDK, is
//!     fine for tests but has no stable layout.
//!   - Two plain (non-generic) exports declared in the root itself, so they stay
//!     bound to the current code under incremental compilation:
//!       `export fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void`
//!       calls `ziggurat.moduleInit(api, gen)`;
//!       `export fn ziggurat_describe() callconv(.c) *const ziggurat.Table`
//!       returns `&table`.
//!   - Scripts are sorted by `rel` (byte order), so the output is deterministic.
//!
//! The build around the root:
//!
//!   - The root module's only dependency is `ziggurat`, so a script can import
//!     only `ziggurat`, `std`, `builtin` and files below the project root. A
//!     script that needs another module (for example gdzig) gets it through a
//!     re-export from the SDK.
//!   - `BuildService.Config.sdk` must contain a module named `ziggurat`;
//!     `BuildService.init` refuses the list otherwise (`error.MissingSdkModule`).
//!     Further SDK modules are listed there too, each with its own deps.
//!   - `@import("root")` from a script or from the SDK is this generated root.
//!
//! The SDK marker (decoded in `diagnostics.zig`): a compile error raised in
//! SDK code has its source location in the SDK, outside the project. To map
//! it to a script, the SDK puts `[ziggurat:<rel>#<name>]` in the message,
//! where `<rel>` is the `rel` argument of `describe` (passed plain by the
//! root) percent-encoded by the SDK: `%` as `%25`, `]` as `%5D`, `:` as `%3A`
//! and `\` as `%5C`; every other byte is written as is. `<name>` is the
//! declaration the error is about (an identifier). The decoder decodes
//! `<rel>`, removes the marker and reports the error at `<rel>`, on the first
//! top-level line that declares `<name>` (line 1 when none does). A marker
//! with any other `%` sequence, or whose decoded path is absolute, has an
//! empty, `.` or `..` part (or, on Windows, contains `:` or `\`), is not a
//! marker: the error then shows without a file and keeps its text.
const std = @import("std");
const builtin = @import("builtin");
const platform = @import("ziggurat_platform");
const scan = @import("scan.zig");
const OsPath = platform.path.OsPath;

pub const root_file_name = ".ziggurat_root.zig";

/// Returns the text of the root file for `scripts`, which the caller frees.
/// `scripts` must already be sorted by `rel` (as `scan.scan` returns them).
/// `build_id` goes into the table as a string literal.
pub fn generateRoot(a: std.mem.Allocator, os: std.Target.Os.Tag, scripts: []const scan.Script, build_id: []const u8) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    try out.appendSlice(a,
        \\//! Generated by Ziggurat. Do not edit; it is rewritten on every build.
        \\
        \\const ziggurat = @import("ziggurat");
        \\
        \\pub const panic = ziggurat.Panic;
        \\
        \\
    );
    for (scripts, 0..) |s, i| {
        const lit = try platform.path.importLiteral(a, os, OsPath.fromTrusted(s.rel));
        defer a.free(lit);
        try out.print(a, "pub const s{d} = ziggurat.describe(@import({s}), \"{f}\");\n", .{ i, lit, std.zig.fmtString(s.rel) });
    }
    try out.appendSlice(a, "\nconst table = ziggurat.makeTable(&.{");
    for (scripts, 0..) |_, i| {
        try out.print(a, "{s} &s{d}", .{ if (i == 0) "" else ",", i });
    }
    try out.print(a, "{s}}}, \"{f}\");\n", .{ if (scripts.len == 0) "" else " ", std.zig.fmtString(build_id) });
    try out.appendSlice(a,
        \\
        \\export fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void {
        \\    ziggurat.moduleInit(api, gen);
        \\}
        \\
        \\export fn ziggurat_describe() callconv(.c) *const ziggurat.Table {
        \\    return &table;
        \\}
        \\
    );
    return out.toOwnedSlice(a);
}

const testing = std.testing;

test "root golden with build id" {
    if (builtin.os.tag == .windows) return error.SkipZigTest;
    const scripts = [_]scan.Script{ .{ .rel = "a/x.zig" }, .{ .rel = "b.zig" } };
    const text = try generateRoot(testing.allocator, .linux, &scripts, "0123456789abcdef");
    defer testing.allocator.free(text);
    try testing.expectEqualStrings(
        \\//! Generated by Ziggurat. Do not edit; it is rewritten on every build.
        \\
        \\const ziggurat = @import("ziggurat");
        \\
        \\pub const panic = ziggurat.Panic;
        \\
        \\pub const s0 = ziggurat.describe(@import("a/x.zig"), "a/x.zig");
        \\pub const s1 = ziggurat.describe(@import("b.zig"), "b.zig");
        \\
        \\const table = ziggurat.makeTable(&.{ &s0, &s1 }, "0123456789abcdef");
        \\
        \\export fn ziggurat_init(api: *const ziggurat.HostApi, gen: u32) callconv(.c) void {
        \\    ziggurat.moduleInit(api, gen);
        \\}
        \\
        \\export fn ziggurat_describe() callconv(.c) *const ziggurat.Table {
        \\    return &table;
        \\}
        \\
    , text);
}

test "generateRoot escapes quotes" {
    if (builtin.os.tag == .windows) return error.SkipZigTest;
    const scripts = [_]scan.Script{.{ .rel = "q\"uote/s.zig" }};
    const text = try generateRoot(testing.allocator, .linux, &scripts, "0000000000000000");
    defer testing.allocator.free(text);
    try testing.expect(std.mem.indexOf(u8, text, "ziggurat.describe(@import(\"q\\\"uote/s.zig\"), \"q\\\"uote/s.zig\");") != null);
}

test "generateRoot with no scripts" {
    const text = try generateRoot(testing.allocator, .linux, &.{}, "fedcba9876543210");
    defer testing.allocator.free(text);
    try testing.expect(std.mem.indexOf(u8, text, "const table = ziggurat.makeTable(&.{}, \"fedcba9876543210\");\n") != null);
    try testing.expect(std.mem.indexOf(u8, text, "ziggurat.describe(") == null);
}

/// True when the dynamic symbol table of the ELF64 little-endian file `bytes`
/// defines `want`.
fn definesDynamicSymbol(bytes: []const u8, want: []const u8) !bool {
    const Ehdr = std.elf.Elf64_Ehdr;
    const Shdr = std.elf.Elf64_Shdr;
    const Sym = std.elf.Elf64_Sym;
    if (bytes.len < @sizeOf(Ehdr)) return error.BadElf;
    const eh = std.mem.bytesToValue(Ehdr, bytes[0..@sizeOf(Ehdr)]);
    if (!std.mem.eql(u8, eh.e_ident[0..4], std.elf.MAGIC)) return error.BadElf;
    const shAt = struct {
        fn get(b: []const u8, h: Ehdr, i: usize) !Shdr {
            const off = h.e_shoff + i * h.e_shentsize;
            if (off + @sizeOf(Shdr) > b.len) return error.BadElf;
            return std.mem.bytesToValue(Shdr, b[off..][0..@sizeOf(Shdr)]);
        }
    }.get;
    for (0..eh.e_shnum) |i| {
        const sh = try shAt(bytes, eh, i);
        if (sh.sh_type != std.elf.SHT_DYNSYM) continue;
        const strsh = try shAt(bytes, eh, sh.sh_link);
        const strtab = bytes[@intCast(strsh.sh_offset)..][0..@intCast(strsh.sh_size)];
        const count: usize = @intCast(sh.sh_size / @sizeOf(Sym));
        for (0..count) |k| {
            const off: usize = @intCast(sh.sh_offset + k * @sizeOf(Sym));
            const sym = std.mem.bytesToValue(Sym, bytes[off..][0..@sizeOf(Sym)]);
            if (sym.st_shndx == std.elf.SHN_UNDEF or sym.st_name >= strtab.len) continue;
            if (std.mem.eql(u8, std.mem.sliceTo(strtab[sym.st_name..], 0), want)) return true;
        }
    }
    return false;
}

test "integration: root compiles against stub sdk" {
    try platform.testing_support.requireIntegration();
    if (builtin.os.tag != .linux) return error.SkipZigTest;
    const build_options = @import("build_options");
    var arena_state = std.heap.ArenaAllocator.init(testing.allocator);
    defer arena_state.deinit();
    const a = arena_state.allocator();
    var tmp = testing.tmpDir(.{});
    defer tmp.cleanup();

    try tmp.dir.createDirPath(testing.io, "sub");
    try tmp.dir.writeFile(testing.io, .{ .sub_path = "one.zig", .data = "pub const extends = \"Node\";\npub fn go() void {}\n" });
    try tmp.dir.writeFile(testing.io, .{ .sub_path = "sub/two.zig", .data = "pub const extends = \"Node2D\";\npub fn bump() void {}\n" });

    const project = OsPath.fromTrusted(try tmp.dir.realPathFileAlloc(testing.io, ".", a));
    const res = try scan.scan(a, testing.io, project, scan.default_script_dirs);
    try testing.expectEqual(@as(usize, 2), res.scripts.len);
    const text = try generateRoot(a, builtin.os.tag, res.scripts, &res.build_id);
    try tmp.dir.writeFile(testing.io, .{ .sub_path = root_file_name, .data = text });

    // The option may be relative to the caller's working directory (the same one
    // the test runs in); make it absolute before the compiler runs elsewhere.
    const stub = try std.Io.Dir.cwd().realPathFileAlloc(testing.io, build_options.stub_sdk_path, a);
    const so = try std.fmt.allocPrint(a, "{s}/libroot.so", .{project.bytes});
    const run = try platform.process.runCapture(a, testing.io, &.{
        build_options.zig_exe,
        "build-lib",
        "-dynamic",
        "-lc",
        try std.fmt.allocPrint(a, "-femit-bin={s}", .{so}),
        "--dep",
        "ziggurat",
        try std.fmt.allocPrint(a, "-Mroot={s}", .{root_file_name}),
        try std.fmt.allocPrint(a, "-Mziggurat={s}", .{stub}),
    }, project, 120_000, 1 << 20);
    if (!run.term.success()) std.debug.print("zig build-lib failed:\n{s}\n", .{run.stderr});
    try testing.expect(run.term.success());

    const bytes = try tmp.dir.readFileAlloc(testing.io, "libroot.so", a, .limited(64 * 1024 * 1024));
    try testing.expect(try definesDynamicSymbol(bytes, "ziggurat_describe"));
    try testing.expect(try definesDynamicSymbol(bytes, "ziggurat_init"));
    try testing.expect(!try definesDynamicSymbol(bytes, "no_such_symbol"));
}
