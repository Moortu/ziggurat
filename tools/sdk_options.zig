//! Build tool: writes the `sdk_options` module.
//!
//! Usage: sdk_options <out.zig> <sdk_version> <precision> <extension_api.json> <gdextension_interface.h>
//!
//! The module holds the SDK version, the hex sha256 of gdzig's two vendored
//! binding inputs (they go into the layout stamp) and the float precision.
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 6) {
        std.debug.print("usage: sdk_options <out.zig> <sdk_version> <precision> <extension_api.json> <gdextension_interface.h>\n", .{});
        std.process.exit(2);
    }
    const api_hex = try sha256Hex(arena, io, args[4]);
    const header_hex = try sha256Hex(arena, io, args[5]);
    const text = try std.fmt.allocPrint(arena,
        \\//! Generated by tools/sdk_options.zig. Do not edit.
        \\pub const sdk_version = "{f}";
        \\pub const api_json_sha256: [64]u8 = "{s}".*;
        \\pub const interface_h_sha256: [64]u8 = "{s}".*;
        \\pub const precision = "{f}";
        \\
    , .{ std.zig.fmtString(args[2]), &api_hex, &header_hex, std.zig.fmtString(args[3]) });
    try std.Io.Dir.cwd().writeFile(io, .{ .sub_path = args[1], .data = text });
}

fn sha256Hex(arena: std.mem.Allocator, io: std.Io, path: []const u8) ![64]u8 {
    const bytes = try std.Io.Dir.cwd().readFileAlloc(io, path, arena, .limited(256 << 20));
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    return std.fmt.bytesToHex(digest, .lower);
}
